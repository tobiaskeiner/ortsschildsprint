create table public.strava_athletes (
  athlete_id bigint primary key,
  display_name text not null,
  profile_image_url text,
  access_token_ciphertext text not null,
  refresh_token_ciphertext text not null,
  access_token_expires_at timestamptz not null,
  granted_scopes text[] not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.strava_athletes enable row level security;

create table public.strava_sessions (
  id uuid primary key default extensions.gen_random_uuid(),
  athlete_id bigint not null references public.strava_athletes (athlete_id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.strava_sessions enable row level security;
create index strava_sessions_athlete_id_idx on public.strava_sessions (athlete_id);
create index strava_sessions_expires_at_idx on public.strava_sessions (expires_at);

create table public.strava_activities (
  activity_id bigint primary key,
  athlete_id bigint not null references public.strava_athletes (athlete_id) on delete cascade,
  processed_at timestamptz not null default now(),
  new_sign_count integer not null default 0 check (new_sign_count >= 0),
  description_updated boolean not null default false
);

alter table public.strava_activities enable row level security;
create index strava_activities_athlete_id_idx on public.strava_activities (athlete_id);

create table public.athlete_city_limit_signs (
  athlete_id bigint not null references public.strava_athletes (athlete_id) on delete cascade,
  osm_id bigint not null,
  first_activity_id bigint not null references public.strava_activities (activity_id) on delete restrict,
  collected_at timestamptz not null,
  primary key (athlete_id, osm_id)
);

alter table public.athlete_city_limit_signs enable row level security;
create index athlete_city_limit_signs_osm_id_idx on public.athlete_city_limit_signs (osm_id);

create table public.strava_webhook_events (
  id bigint generated by default as identity primary key,
  object_type text not null,
  object_id bigint not null,
  aspect_type text not null,
  owner_id bigint not null,
  event_time timestamptz not null,
  updates jsonb not null default '{}'::jsonb,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  unique (object_type, object_id, aspect_type, event_time)
);

alter table public.strava_webhook_events enable row level security;

create or replace function public.signs_near_route(
  route_geojson jsonb,
  max_distance_meters double precision default 10
)
returns table (
  osm_id bigint,
  tags jsonb,
  lat double precision,
  long double precision
)
language sql
stable
set search_path = ''
as $$
  with route as (
    select extensions.st_setsrid(
      extensions.st_geomfromgeojson(route_geojson::text),
      4326
    )::extensions.geography as geography
  )
  select
    sign.osm_id,
    sign.tags,
    extensions.st_y(sign.location::extensions.geometry) as lat,
    extensions.st_x(sign.location::extensions.geometry) as long
  from public.city_limit_signs as sign
  cross join route
  where extensions.st_dwithin(sign.location, route.geography, max_distance_meters)
$$;
