-- Strava can emit distinct updates for the same object and second. Keep the
-- application-generated fingerprint as the idempotency key instead of
-- collapsing all events that share the old four-column tuple.
alter table public.strava_webhook_events
  add column event_fingerprint text;

-- Existing rows predate the application fingerprint. A hash of their stable
-- identity gives each row a deterministic, valid value without conflating it
-- with future event fingerprints.
update public.strava_webhook_events
set event_fingerprint = encode(
  extensions.digest(convert_to(id::text, 'UTF8'), 'sha256'),
  'hex'
)
where event_fingerprint is null;

alter table public.strava_webhook_events
  alter column event_fingerprint set not null,
  add constraint strava_webhook_events_event_fingerprint_format_check
    check (event_fingerprint ~ '^[0-9a-f]{64}$');

-- The autogenerated name of the original constraint may be truncated, so
-- locate it by its columns rather than relying on a generated identifier.
do $$
declare
  old_constraint_name text;
begin
  select constraint_definition.conname
  into old_constraint_name
  from pg_constraint as constraint_definition
  where constraint_definition.conrelid =
      'public.strava_webhook_events'::regclass
    and constraint_definition.contype = 'u'
    and (
      select array_agg(attribute.attname::text order by key_column.ordinality)
      from unnest(constraint_definition.conkey) with ordinality as key_column(
        attnum,
        ordinality
      )
      join pg_attribute as attribute
        on attribute.attrelid = constraint_definition.conrelid
        and attribute.attnum = key_column.attnum
    ) = array['object_type', 'object_id', 'aspect_type', 'event_time']::text[];

  if old_constraint_name is not null then
    execute format(
      'alter table public.strava_webhook_events drop constraint %I',
      old_constraint_name
    );
  end if;
end;
$$;

alter table public.strava_webhook_events
  add constraint strava_webhook_events_event_fingerprint_key
    unique (event_fingerprint);
